<?php

namespace App\Services;

use App\Enums\ClanActionType;
use App\Enums\ClanBonusType;
use App\Exceptions\ClanException;
use App\Models\Clan;
use App\Models\ClanAction;
use App\Models\ClanBonus;
use App\Models\ClanMission;
use App\Models\ClanMissionStep;
use App\Models\Game;
use App\Models\Period;
use App\Models\Run;
use App\Models\User;
use Illuminate\Support\Facades\DB;

// the collaborative missions of the clans: a series of scores to reach on several games within
// kado.clans.mission_hours. A completed mission gives mission points to the clan and sometimes a bonus.
class ClanMissionService
{
    public function __construct(
        private readonly ClanService $clanService,
        private readonly GameService $gameService,
    ) {}

    // the mission in progress (a new one when the previous is over)
    public function currentMission(Clan $clan, ?Period $period = null): ?ClanMission
    {
        $period ??= $this->clanService->currentPeriod();
        if (!$period) {
            return null;
        }

        ClanMission::query()
            ->where('clan_id', $clan->id)
            ->where('period_id', $period->id)
            ->where('status', ClanMission::ACTIVE)
            ->where('expires_at', '<=', now())
            ->update(['status' => ClanMission::FAILED]);

        $mission = ClanMission::query()
            ->where('clan_id', $clan->id)
            ->where('period_id', $period->id)
            ->where('status', ClanMission::ACTIVE)
            ->first();

        if (!$mission && $period->end_at->isFuture()) {
            $mission = $this->generateMission($clan, $period);
        }

        return $mission;
    }

    public function generateMission(Clan $clan, Period $period): ClanMission
    {
        return DB::transaction(function () use ($clan, $period) {
            $score = $this->clanService->periodScore($clan, $period);
            $score = $score->newQuery()->lockForUpdate()->find($score->id);
            // generated by another request in the meantime
            $active = ClanMission::query()->where('clan_id', $clan->id)->where('period_id', $period->id)
                ->where('status', ClanMission::ACTIVE)->where('expires_at', '>', now())->first();
            if ($active) {
                return $active;
            }

            $number = (int) ClanMission::query()->where('clan_id', $clan->id)->where('period_id', $period->id)->max('number') + 1;
            $mission = ClanMission::query()->create([
                'clan_id' => $clan->id,
                'period_id' => $period->id,
                'number' => $number,
                'status' => ClanMission::ACTIVE,
                'double_points' => $score->next_mission_double,
                'expires_at' => now()->addHours((int) config('kado.clans.mission_hours')),
            ]);
            if ($score->next_mission_double) {
                $score->update(['next_mission_double' => false]);
            }

            foreach ($this->pickGames($score->banned_game_id, $score->forced_game_id) as $game) {
                $target = max(1, $this->gameService->generateScore($game->stars));
                $mission->steps()->create([
                    'game_id' => $game->id,
                    'target_score' => $target,
                    'points' => $this->stepPoints($game, $target),
                ]);
            }

            return $mission->load('steps');
        });
    }

    public function startStep(User $user, ClanMissionStep $step): ClanAction
    {
        $mission = $step->mission;
        $this->clanService->assertMember($user, $mission->clan);
        if ($mission->status !== ClanMission::ACTIVE || $mission->expires_at->isPast()) {
            throw new ClanException('Cette mission est terminée.');
        }
        if ($step->isDone()) {
            throw new ClanException('Cette étape a déjà été réussie.');
        }

        return ClanAction::query()->create([
            'clan_id' => $mission->clan_id,
            'user_id' => $user->id,
            'game_id' => $step->game_id,
            'type' => ClanActionType::MISSION,
            'clan_mission_step_id' => $step->id,
        ]);
    }

    public function completeStep(ClanAction $action, Run $run): string
    {
        return DB::transaction(function () use ($action, $run) {
            $step = ClanMissionStep::query()->lockForUpdate()->findOrFail($action->clan_mission_step_id);
            $mission = $step->mission;

            if ($step->isDone() || $mission->status !== ClanMission::ACTIVE || $mission->expires_at->isPast()) {
                return 'too_late';
            }
            if ($run->score < $step->target_score) {
                return 'failed';
            }

            $step->update([
                'completed_by_user_id' => $action->user_id,
                'run_id' => $run->id,
                'score' => $run->score,
                'completed_at' => now(),
            ]);
            $this->clanService->memberStat($mission->clan_id, $action->user_id, $mission->period_id)->increment('mission_steps');
            $this->completeMissionIfDone($mission);

            return 'completed';
        });
    }

    // ---------------------------------------------------------------- bonuses

    /**
     * @param  array{game_id?: int, step_id?: int}  $params
     */
    public function useBonus(User $user, ClanBonus $bonus, array $params = []): void
    {
        $clan = $bonus->clan;
        $this->clanService->assertLeader($user, $clan);
        $this->assertUsable($bonus);
        if ($bonus->type->isAssignable()) {
            throw new ClanException('Cette option s\'utilise au moment d\'attaquer ou de défendre.');
        }
        $period = $this->clanService->assertPeriod();

        DB::transaction(function () use ($bonus, $clan, $period, $params) {
            $score = $this->clanService->periodScore($clan, $period);
            $mission = $this->currentMission($clan, $period);
            if (!$mission && in_array($bonus->type, [ClanBonusType::MORE_TIME, ClanBonusType::SKIP_STEP], true)) {
                throw new ClanException('Aucune mission en cours.');
            }

            switch ($bonus->type) {
                case ClanBonusType::NEXT_MISSION:
                    $mission?->update(['status' => ClanMission::SKIPPED]);
                    $this->generateMission($clan, $period);
                    break;
                case ClanBonusType::DOUBLE_POINTS:
                    $score->update(['next_mission_double' => true]);
                    break;
                case ClanBonusType::BAN_GAME:
                    $game = $this->activeGame($params['game_id'] ?? null);
                    $score->update([
                        'banned_game_id' => $game->id,
                        'forced_game_id' => $score->forced_game_id === $game->id ? null : $score->forced_game_id,
                    ]);
                    break;
                case ClanBonusType::FORCE_GAME:
                    $game = $this->activeGame($params['game_id'] ?? null);
                    $score->update([
                        'forced_game_id' => $game->id,
                        'banned_game_id' => $score->banned_game_id === $game->id ? null : $score->banned_game_id,
                    ]);
                    break;
                case ClanBonusType::MORE_TIME:
                    $mission->update(['expires_at' => $mission->expires_at->addHours((int) config('kado.clans.mission_more_time_hours'))]);
                    break;
                case ClanBonusType::SKIP_STEP:
                    $step = $mission->steps()->whereKey($params['step_id'] ?? 0)->first();
                    if (!$step || $step->isDone()) {
                        throw new ClanException('Choisissez une étape de la mission en cours qui n\'est pas encore réussie.');
                    }
                    $step->update(['skipped' => true]);
                    $this->completeMissionIfDone($mission);
                    break;
                default:
                    break;
            }

            $bonus->update(['used_at' => now()]);
        });
    }

    // "Double attaque" and "Défense 120%" are given by the leader to a member, who uses it himself
    public function assignBonus(User $leader, ClanBonus $bonus, User $member): void
    {
        $this->clanService->assertLeader($leader, $bonus->clan);
        $this->assertUsable($bonus);
        if (!$bonus->type->isAssignable()) {
            throw new ClanException('Seules les options Double attaque et Défense 120% peuvent être données à un joueur.');
        }
        $this->clanService->assertMember($member, $bonus->clan);

        $bonus->update(['assigned_user_id' => $member->id]);
    }

    // ---------------------------------------------------------------- internals

    private function completeMissionIfDone(ClanMission $mission): void
    {
        $steps = $mission->steps()->get();
        if ($steps->contains(fn (ClanMissionStep $step) => !$step->isDone())) {
            return;
        }

        $points = $steps->where('skipped', false)->sum('points') * ($mission->double_points ? 2 : 1);
        $mission->update(['status' => ClanMission::COMPLETED, 'points' => $points, 'completed_at' => now()]);

        $score = $this->clanService->periodScore($mission->clan, $mission->period);
        $score->increment('mission_score', $points);
        $score->increment('missions_completed');

        if (randomNumber() < (float) config('kado.clans.bonus_chance')) {
            $types = ClanBonusType::cases();
            ClanBonus::query()->create([
                'clan_id' => $mission->clan_id,
                'period_id' => $mission->period_id,
                'type' => $types[array_rand($types)],
            ]);
        }
    }

    private function assertUsable(ClanBonus $bonus): void
    {
        if ($bonus->used_at !== null) {
            throw new ClanException('Cette option a déjà été utilisée.');
        }
        if ($bonus->period_id !== $this->clanService->currentPeriod()?->id) {
            throw new ClanException('Les options sont remises à zéro à la fin du tournoi des clans.');
        }
    }

    private function activeGame(?int $gameId): Game
    {
        $game = $gameId ? Game::query()->where('is_active', true)->find($gameId) : null;
        if (!$game) {
            throw new ClanException('Choisissez un jeu.');
        }

        return $game;
    }

    /**
     * @return \Illuminate\Support\Collection<int, Game>
     */
    private function pickGames(?int $bannedGameId, ?int $forcedGameId)
    {
        $count = (int) config('kado.clans.mission_steps');
        $games = Game::query()
            ->where('is_active', true)
            ->where('is_arkadeo', false)
            ->when($bannedGameId, fn ($q) => $q->where('id', '!=', $bannedGameId))
            ->get()
            ->filter(fn (Game $game) => is_array($game->stars) && count($game->stars) >= 3)
            ->shuffle();

        $forced = $forcedGameId ? $games->firstWhere('id', $forcedGameId) : null;
        if ($forced) {
            $games = $games->reject(fn (Game $game) => $game->id === $forced->id)->prepend($forced);
        }

        return $games->take($count)->values();
    }

    // 1 to 10 points, the closer to the red star the more points
    private function stepPoints(Game $game, int $target): int
    {
        $max = max(1, (int) max($game->stars));

        return max(1, min(10, (int) ceil($target / $max * 10)));
    }
}
